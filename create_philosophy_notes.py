output_dir = "/home/meteof/proj/bullet_journal/notes/philosophy"


def sanitize_filename(text):
    # Remove characters that are problematic for filenames
    text = re.sub(r'[\\/*?:"<>|]', "", text)
    # Replace spaces with underscores
    text = text.strip().replace(" ", "_").replace("\n", "_")
    # Limit length
    return text[:100]


# Pre-process raw text to merge lines describing the same topic and remove standalone numbers
lines = topics_raw.strip().split("\n")
topics = []
current_topic = ""

for line in lines:
    line = line.strip()
    if not line:
        continue
    # Check if it's a page number (like '8' or '9' alone)
    if re.match(r"^\d+$", line):
        continue
    # Check if it starts with a topic number (e.g. "1. ")
    if re.match(r"^\d+\.", line):
        if current_topic:
            topics.append(current_topic)
        current_topic = line
    else:
        # Append to current topic if it's a continuation
        if current_topic:
            current_topic += " " + line
        else:
            current_topic = line

if current_topic:
    topics.append(current_topic)

for topic in topics:
    match = re.match(r"^(\d+)\.\s*(.*)", topic)
    if match:
        num = int(match.group(1))
        content = match.group(2)
        filename = f"{num:02d}_{sanitize_filename(content)}.md"
        path = os.path.join(output_dir, filename)
        with open(path, "w", encoding="utf-8") as f:
            f.write(f"# {topic}\n")

print(f"Created {len(topics)} files in {output_dir}")
